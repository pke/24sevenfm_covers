function stem(country, system, rating) {
  return [country, system, rating].join("_").toLowerCase().replace(/[^a-z0-9]+/g, "_");
}

function cppBytes(buffer) {
  const rows = [];
  for (let i = 0; i < buffer.length; i += 16)
    rows.push("    " + [...buffer.subarray(i, i + 16)].map(v => "0x" + v.toString(16).padStart(2, "0")).join(", "));
  return rows.join(",\n");
}

async function download(url) {
  for (let attempt = 0; attempt < 6; ++attempt) {
    const response = await fetch(url, { headers: { "User-Agent": "24sevenfm-covers-asset-builder/1.0 (local deterministic build)" } });
    if (response.ok) return Buffer.from(await response.arrayBuffer());
    if (response.status !== 429 && response.status < 500)
      throw new Error(`${response.status} ${url}`);
    const retryAfter = Number(response.headers.get("retry-after"));
    await new Promise(resolve => setTimeout(resolve,
      Number.isFinite(retryAfter) ? retryAfter * 1000 : 1500 * (attempt + 1)));
  }
  throw new Error(`rate limited while downloading ${url}`);
}

function tvGuidelinesSvg(rating) {
  const lines = rating === "TV-Y7-FV" ? ["TV-Y7", "FV"] : [rating];
  const text = lines.length === 1
    ? `<text x="256" y="305" text-anchor="middle" font-family="Arial,sans-serif" font-weight="900" font-size="150">${lines[0]}</text>`
    : `<text x="256" y="244" text-anchor="middle" font-family="Arial,sans-serif" font-weight="900" font-size="126">${lines[0]}</text><text x="256" y="374" text-anchor="middle" font-family="Arial,sans-serif" font-weight="900" font-size="116">${lines[1]}</text>`;
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512"><rect x="13" y="13" width="486" height="486" rx="72" fill="#fff" stroke="#000" stroke-width="26"/><rect x="49" y="49" width="414" height="414" rx="40" fill="#000"/><g fill="#fff">${text}</g></svg>`);
}

(async () => {
  await fs.mkdir(output, { recursive: true });
  const generated = ["// Generated by tools/generate-rating-assets.js. Do not edit."];
  const table = [];
  for (const [country, system, rating, url] of entries) {
    const name = stem(country, system, rating);
    const target = path.join(output, name + ".png");
    let png;
    try { png = await fs.readFile(target); }
    catch {
      const svg = system === "TV Parental Guidelines"
        ? tvGuidelinesSvg(rating) : await download(url);
      png = await sharp(svg, { density: 288 })
        .resize({ width: 512, height: 256, fit: "inside", withoutEnlargement: false })
        .png({ compressionLevel: 9, palette: true, quality: 92, effort: 10 })
        .toBuffer();
      await fs.writeFile(target, png);
      await new Promise(resolve => setTimeout(resolve, 350));
    }
    generated.push(`static const unsigned char k_${name}[] = {\n${cppBytes(png)}\n};`);
    table.push(`    { "${country}", "${system}", "${rating}", k_${name}, sizeof(k_${name}) }`);
  }
  generated.push("static const RatingAssetData kRatingAssets[] = {\n" + table.join(",\n") + "\n};", "");
  await fs.writeFile(path.join(root, "shared", "rating_assets.generated.inc"), generated.join("\n"));
})().catch(error => { console.error(error); process.exitCode = 1; });
